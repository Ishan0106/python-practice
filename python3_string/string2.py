# operation on string

# concatination
s1 = 'ccv'
s2 = 'fscs'
s3 = s1 + s2
print(s3)

# repitition
s2 = s1 * 5
print(s2)

# membership (in , not in)
if 's' in s1:
    print('yes')
else:
    print('not')

# string comparison < , <= , >= , ==, !=
if s1 != s2:
    print('mvfevrv')

if s1 < s2:
    print('vsdfvsd')

